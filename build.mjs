#!/usr/bin/env node
// Builds the static site into docs/ (what GitHub Pages serves). No dependencies.
//   node build.mjs                 -> ./docs
//   node build.mjs --out DIR       -> DIR
//   node build.mjs --test-clip     -> copy review/test-clip hero files into OUT/assets/hero
//                                     (never the default for docs/; tests fail if they land there)
import { mkdirSync, rmSync, writeFileSync, readdirSync, copyFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE, liveServices } from './site.config.mjs';
import { PAGES } from './src/pages.mjs';
import { makeCtx, renderPage } from './src/layout.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outArg = process.argv.indexOf('--out');
const OUT = outArg > -1 ? process.argv[outArg + 1] : join(here, 'docs');
const useTestClip = process.argv.includes('--test-clip');

function copyDir(from, to) {
  if (!existsSync(from)) return;
  mkdirSync(to, { recursive: true });
  for (const name of readdirSync(from)) {
    if (name.startsWith('.')) continue;
    const a = join(from, name), b = join(to, name);
    if (statSync(a).isDirectory()) copyDir(a, b); else copyFileSync(a, b);
  }
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
copyDir(join(here, 'src/assets'), join(OUT, 'assets'));

if (useTestClip) {
  const testDir = join(here, 'review/test-clip');
  if (!existsSync(testDir)) {
    console.error('Missing review/test-clip/. Run tools/make-test-clip.sh first.');
    process.exit(1);
  }
  copyDir(testDir, join(OUT, 'assets/hero'));
}

const has16 = existsSync(join(OUT, 'assets/hero/mm-hero-scrub-16x9.mp4'));
const has9 = existsSync(join(OUT, 'assets/hero/mm-hero-scrub-9x16.mp4'));

const browserConfig = {
  phoneE164: SITE.phone.e164,
  leadEndpoint: SITE.leadEndpoint,
  hero: {
    duration: SITE.hero.duration,
    holdFrom: SITE.hero.holdFrom,
    has16,
    has9,
  },
};
writeFileSync(join(OUT, 'assets/config.js'),
  `/* Generated by build.mjs from site.config.mjs. */\nwindow.MM_CONFIG = ${JSON.stringify(browserConfig)};\n`);

const sitemap = [];
for (const page of PAGES) {
  const is404 = page.slug === '404';
  const ctx = makeCtx(SITE, page.slug, { absolute: is404, hasHeroVideo: has16 || has9 });
  const html = renderPage(ctx, page);
  const rel = page.file || (page.slug ? `${page.slug}/index.html` : 'index.html');
  mkdirSync(dirname(join(OUT, rel)), { recursive: true });
  writeFileSync(join(OUT, rel), html);
  if (page.inSitemap !== false && !page.noindex) {
    sitemap.push({ loc: ctx.abs(page.slug ? `${page.slug}/` : ''), priority: page.slug ? (page.slug === 'free-estimate' ? '0.9' : '0.8') : '1.0' });
  }
}

writeFileSync(join(OUT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemap.map((u) => `  <url><loc>${u.loc}</loc><lastmod>${SITE.updated}</lastmod><priority>${u.priority}</priority></url>`).join('\n')}
</urlset>
`);

writeFileSync(join(OUT, 'robots.txt'), SITE.launched
  ? `User-agent: *\nAllow: /\n\nSitemap: ${SITE.url.replace(/\/$/, '')}/sitemap.xml\n`
  : `# Preview build: not launched. Flip launched: true in site.config.mjs at launch.\nUser-agent: *\nDisallow: /\n`);

writeFileSync(join(OUT, '.nojekyll'), '');
if (SITE.customDomain) writeFileSync(join(OUT, 'CNAME'), `${SITE.customDomain}\n`);

const live = liveServices(SITE).map((s) => s.slug).join(', ');
console.log(`Built ${PAGES.length} pages into ${OUT} (${SITE.launched ? 'LAUNCHED' : 'preview, noindex'}). Services: ${live || '(none)'}.${useTestClip ? ' TEST CLIP loaded.' : ''}`);
